#!/usr/bin/env python3
"""Rebuild the approved G audition as a static browser PCM bank.

Usage from the repository root:
    python tools/build_slash_samples.py
    python tools/build_slash_samples.py --check

Requires numpy and scipy.  The optional --verify-wav-dir argument additionally
compares complete generated WAV bytes with the original audition exports; the
normal build verifies the embedded approved hashes and needs no scratch files.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import importlib.util
import io
import json
from pathlib import Path

import numpy as np
from scipy.io import wavfile

ROOT = Path(__file__).resolve().parents[1]
GENERATOR = ROOT / "tools" / "audio" / "slash_g.py"
SAMPLE_RATE = 48000
CHANNELS = 2
GAIN = 0.8072350302488382
KEYS = ("shoot", "hit", "kill", "gem", "signature")

# Frames, normalized PCM16LE SHA-256, and complete original WAV SHA-256.
# These hashes anchor the asset to the samples selected by the user.
APPROVED = {
    "shoot": (7584,
              "39d28ec3a79e1956181ac9d71461ae27e229acdb533258b67dbf6a78fc08a7a5",
              "d4aa57d92637287b59e6b602c9433b363b2d5dd4e8f580efe4c3ba887b52a51a"),
    "hit": (3984,
            "9969d19e99a8b2df5459c87f9e7c5ae221e13bba385f8c4d8905975f43853006",
            "212745c70fb129597a5e7d38fe45620159772d62d951d8d132b95cf1e548f1cf"),
    "kill": (15600,
             "2e2e500b3acc54d91c56db6025eb895e6f069cb1c9a24fbf6e09d443f110cad0",
             "4c97e5c06ee5ddbf45af3b4ea3cebf363cf9f457a8e99e44e9851a0f5c73c8ff"),
    "gem": (8736,
            "bda4ff4e99661123242693723ea60b87c2e395e5c805f5df9684d4154e10a09d",
            "8695a5d29a073d42bedbf4bee9e2f2d10e13bdf00b5852427aa6c0c947a636aa"),
    "signature": (117600,
                  "b61096602c90f48e9f1acc041e2474d9478f9a7b6c404f96af65d9b96f596748",
                  "8d8b1218a9782f48e3ff2dc1bc35aeb0a86a88868382be86f5ce759a1b08a351"),
}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def make_asset(verify_wav_dir: Path | None = None) -> tuple[bytes, dict]:
    spec = importlib.util.spec_from_file_location("ruu_slash_g", GENERATOR)
    if spec is None or spec.loader is None:
        raise RuntimeError("Unable to load the checked-in G generator")
    generator = importlib.util.module_from_spec(spec)
    # Execute the checked-in source without leaving generated __pycache__ files
    # beside the reproducible source in the repository.
    exec(compile(GENERATOR.read_bytes(), str(GENERATOR), "exec"), generator.__dict__)
    bank = generator.build(SAMPLE_RATE)
    if set(bank) != set(KEYS):
        raise ValueError("Unexpected cue set")

    provenance = {
        "audition": "RUU_SFX_G_Slash",
        "generator": "tools/audio/slash_g.py",
        "generatorSha256": sha256(GENERATOR.read_bytes()),
        "linearGain": GAIN,
        "quantization": "round-to-nearest-even(float64 * linearGain * 32767)",
        "playbackDecode": "signed little-endian int16 / 32768",
    }
    lines = [
        "/* RUU//OVERRUN - approved G / SLASH WIND sample bank.",
        "   Generated by tools/build_slash_samples.py; do not edit by hand.",
        "   Exact normalized audition PCM. No audio decoding occurs on load. */",
        "(()=>{",
        "'use strict';",
        "window.RUU_SLASH_SAMPLES = {",
        "  sampleRate: 48000,",
        "  channels: 2,",
        "  format: 's16le',",
        "  provenance: " + json.dumps(provenance, ensure_ascii=True, separators=(",", ":")) + ",",
        "  cues: {",
    ]
    report = {}
    for key in KEYS:
        x = bank[key]
        frames, approved_pcm_hash, approved_wav_hash = APPROVED[key]
        if (x.dtype != np.float64 or x.shape != (frames, CHANNELS)
                or not np.isfinite(x).all() or np.max(np.abs(x * GAIN)) >= 1):
            raise ValueError(f"Invalid source waveform: {key}")
        if np.any(x[0]) or np.any(x[-1]):
            raise ValueError(f"Nonzero source edge: {key}")

        # Exactly the original audition's linear gain and PCM16 rounding.
        pcm = np.rint(x * GAIN * 32767).astype("<i2")
        pcm_bytes = pcm.tobytes(order="C")
        stream = io.BytesIO()
        wavfile.write(stream, SAMPLE_RATE, pcm)
        wav_bytes = stream.getvalue()
        pcm_hash, wav_hash = sha256(pcm_bytes), sha256(wav_bytes)
        if pcm_hash != approved_pcm_hash or wav_hash != approved_wav_hash:
            raise ValueError(f"Generated {key} differs from the approved audition")
        source_file = f"G_{key}.wav"
        if verify_wav_dir is not None:
            original = (verify_wav_dir / source_file).read_bytes()
            if original != wav_bytes:
                raise ValueError(f"Whole-file comparison failed for {source_file}")

        encoded = base64.b64encode(pcm_bytes).decode("ascii")
        metadata = {
            "frames": frames,
            "sourceFile": source_file,
            "pcmSha256": pcm_hash,
            "wavSha256": wav_hash,
        }
        lines.append("    " + json.dumps(key) + ": {")
        for field, value in metadata.items():
            lines.append("      " + json.dumps(field) + ": " + json.dumps(value) + ",")
        lines.append("      pcm: [")
        for at in range(0, len(encoded), 1024):
            lines.append("        " + json.dumps(encoded[at:at + 1024]) + ",")
        lines += ["      ].join('')", "    },"]
        report[key] = {**metadata, "duration": frames / SAMPLE_RATE, "pcmBytes": len(pcm_bytes)}
    lines += ["  }", "};", "})();", ""]
    return "\n".join(lines).encode("utf-8"), report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "audio-slash-samples.js")
    parser.add_argument("--verify-wav-dir", type=Path,
                        help="Optional directory containing the five original G_*.wav exports")
    parser.add_argument("--check", action="store_true",
                        help="Verify that the existing JS is byte-identical; do not rewrite it")
    args = parser.parse_args()
    content, cues = make_asset(args.verify_wav_dir)
    if args.check:
        if args.output.read_bytes() != content:
            raise SystemExit("The checked-in sample bank differs from the approved build")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(content)
    print(json.dumps({"file": str(args.output), "bytes": len(content),
                      "sha256": sha256(content), "verified": True, "cues": cues}, indent=2))


if __name__ == "__main__":
    main()
